import 'package:firebase_app_check/firebase_app_check.dart';

/// reCAPTCHA Enterprise key ID registered in Firebase App Check for the Pocko
/// web app. Legacy reCAPTCHA v3 is closed to new Firebase apps, so production
/// web builds use the Enterprise provider.
///
/// The same key lives in `web/firebase_ai_web.js` (the dedicated AI Logic app);
/// `test/app_check_config_test.dart` fails if the two ever drift apart.
/// Override at build time with `--dart-define=RECAPTCHA_ENTERPRISE_SITE_KEY=...`.
const String kRecaptchaEnterpriseKeyId = String.fromEnvironment(
  'RECAPTCHA_ENTERPRISE_SITE_KEY',
  defaultValue: '6LeQFiguAAAAAHICeYz3HNnYpDmBOdzDzNkJ9k72',
);

/// Token string that makes the web SDK use its debug provider. The real debug
/// token is generated by the SDK (see `FIREBASE_APPCHECK_DEBUG_TOKEN` in
/// `web/firebase_ai_web.js`) and registered once in the Firebase console.
const String kWebDebugTokenPlaceholder = 'debug-token-local-development';

/// Hosts where the App Check *debug* provider is allowed on the web.
bool isLocalWebHost(String host) =>
    host == 'localhost' || host == '127.0.0.1' || host == '[::1]';

/// Firebase Hosting production hosts (`<project>.web.app` / `.firebaseapp.com`).
bool isProductionWebHost(String host) =>
    host.endsWith('.web.app') || host.endsWith('.firebaseapp.com');

/// True once a real key ID replaced the placeholder.
bool hasRealRecaptchaKey([String key = kRecaptchaEnterpriseKeyId]) =>
    key.trim().length > 8 && !key.startsWith('PASTE_');

/// Web App Check provider for [host]: the debug provider only on localhost,
/// reCAPTCHA Enterprise everywhere else (production hosts and any other origin,
/// so a debug token can never be used on a public site).
WebProvider webAppCheckProvider(
  String host, {
  String key = kRecaptchaEnterpriseKeyId,
  bool forceDebug = false,
}) {
  if (forceDebug || isLocalWebHost(host)) {
    return ReCaptchaEnterpriseProvider(kWebDebugTokenPlaceholder);
  }
  return ReCaptchaEnterpriseProvider(key);
}
